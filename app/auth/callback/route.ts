import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

export async function GET(request: Request) {
  const url = new URL(request.url);
  const code = url.searchParams.get("code");
  const nextValue = url.searchParams.get("next") ?? "/";
  const next = nextValue.startsWith("/") && !nextValue.startsWith("//") ? nextValue : "/";
  const supabase = await createClient();
  if (code && supabase) {
    const { error } = await supabase.auth.exchangeCodeForSession(code);
    if (!error) return NextResponse.redirect(new URL(next, url.origin));
  }
  return NextResponse.redirect(new URL("/auth/sign-in?error=Authentication%20link%20is%20invalid%20or%20expired.", url.origin));
}
